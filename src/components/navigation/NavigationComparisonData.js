export function calculateWeightedScore(scores) {
  let totalWeighted = 0;
  let totalWeight = 0;
  for (const crit of COMPARISON_CRITERIA) {
    totalWeighted += (scores[crit.key] || 0) * crit.weight;
    totalWeight += crit.weight;
  }
  return Number((totalWeighted / totalWeight).toFixed(2));
}
